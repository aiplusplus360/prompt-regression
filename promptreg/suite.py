"""Suite loading and validation.

A suite is JSON — deliberately, so the tool has zero dependencies and a suite
can be generated by anything. YAML would be prettier for multi-line prompts but
it would also mean shipping a parser, and a prompt-testing tool that fails to
install is a prompt-testing tool nobody runs in CI.

Validation is strict and happens before any model call: a typo in a case file
should cost you a second, not a hundred paid requests.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence


class SuiteError(ValueError):
    """The suite file is malformed."""


@dataclass
class Case:
    id: str
    prompt: str
    expected: str = ""
    system: Optional[str] = None
    contains: Sequence[str] = field(default_factory=tuple)
    excludes: Sequence[str] = field(default_factory=tuple)
    min_similarity: float = 0.0
    max_chars: Optional[int] = None
    min_chars: Optional[int] = None

    @classmethod
    def from_dict(cls, index: int, raw: Dict[str, Any]) -> "Case":
        where = f"case #{index}"
        if not isinstance(raw, dict):
            raise SuiteError(f"{where} must be an object")

        case_id = raw.get("id")
        if not case_id or not isinstance(case_id, str):
            raise SuiteError(f"{where} is missing a string 'id'")

        prompt = raw.get("prompt")
        if not prompt or not isinstance(prompt, str):
            raise SuiteError(f"case {case_id!r} is missing a string 'prompt'")

        for key in ("contains", "excludes"):
            value = raw.get(key, ())
            if not isinstance(value, (list, tuple)):
                raise SuiteError(f"case {case_id!r}: {key!r} must be a list")

        threshold = raw.get("min_similarity", 0.0)
        if not isinstance(threshold, (int, float)) or not 0.0 <= threshold <= 1.0:
            raise SuiteError(
                f"case {case_id!r}: 'min_similarity' must be a number in [0, 1]"
            )

        # A baseline is required to score similarity. Asking for a threshold
        # without one silently passes every case, which is worse than an error.
        if threshold > 0 and not raw.get("expected"):
            raise SuiteError(
                f"case {case_id!r}: 'min_similarity' needs an 'expected' baseline"
            )

        return cls(
            id=case_id,
            prompt=prompt,
            expected=raw.get("expected", "") or "",
            system=raw.get("system"),
            contains=tuple(raw.get("contains", ()) or ()),
            excludes=tuple(raw.get("excludes", ()) or ()),
            min_similarity=float(threshold),
            max_chars=raw.get("max_chars"),
            min_chars=raw.get("min_chars"),
        )


@dataclass
class Suite:
    name: str
    cases: List[Case]

    def __len__(self) -> int:
        return len(self.cases)

    def __iter__(self):
        return iter(self.cases)


def load_suite(path: str | Path) -> Suite:
    """Parse and validate a suite file."""
    path = Path(path)
    if not path.exists():
        raise SuiteError(f"no such suite: {path}")

    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SuiteError(f"{path} is not valid JSON: {exc}") from exc

    if isinstance(raw, list):
        raw = {"name": path.stem, "cases": raw}
    if not isinstance(raw, dict):
        raise SuiteError(f"{path} must contain an object or a list of cases")

    cases_raw = raw.get("cases")
    if not isinstance(cases_raw, list) or not cases_raw:
        raise SuiteError(f"{path} has no 'cases'")

    cases = [Case.from_dict(i, c) for i, c in enumerate(cases_raw)]

    seen = set()
    for case in cases:
        if case.id in seen:
            raise SuiteError(f"duplicate case id: {case.id!r}")
        seen.add(case.id)

    return Suite(name=raw.get("name") or path.stem, cases=cases)


def dump_suite(suite: Suite) -> Dict[str, Any]:
    """Serialize back to the on-disk shape (used by --update-baseline)."""
    return {
        "name": suite.name,
        "cases": [
            {
                "id": c.id,
                "prompt": c.prompt,
                **({"system": c.system} if c.system else {}),
                "expected": c.expected,
                **({"contains": list(c.contains)} if c.contains else {}),
                **({"excludes": list(c.excludes)} if c.excludes else {}),
                **({"min_similarity": c.min_similarity} if c.min_similarity else {}),
                **({"max_chars": c.max_chars} if c.max_chars is not None else {}),
                **({"min_chars": c.min_chars} if c.min_chars is not None else {}),
            }
            for c in suite.cases
        ],
    }
